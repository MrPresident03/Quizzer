android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.brainblitz.qyzwxu"
    minSdk = 26
    targetSdk = 36
    // CI builds are numbered by the workflow run, so each new APK installs as an update.
    val ciBuildNumber = System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull()
    versionCode = ciBuildNumber ?: 1
    versionName = if (ciBuildNumber != null) "1.1.$ciBuildNumber" else "1.1-dev"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      // A fixed debug key is committed (debug.keystore) so every build - CI or local - is signed
      // the same way and new APKs install over the old one without losing progress. It is only a
      // debug key: use a private release key (kept out of git) for Play Store builds.
      if (file("${rootDir}/debug.keystore").exists()) {
        signingConfig = signingConfigs.getByName("debugConfig")
      }
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
}

// KSP (Room/Moshi code generation) is only needed for the app's own sources; tests don't use those
// annotations, so skip it for test source sets. Note: KSP2 may log a harmless
// "ApplicationManager.getApplication() is null" NullPointerException from a background thread.
tasks.configureEach {
  if (name.startsWith("ksp") && (name.endsWith("UnitTestKotlin") || name.endsWith("AndroidTestKotlin"))) {
    enabled = false
  }
}

