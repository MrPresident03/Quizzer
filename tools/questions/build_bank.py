#!/usr/bin/env python3
"""Merge curated + fetched sources into app/src/main/assets/questions.json and STATS.md."""
import collections
import json
import os
import re
import sys

import qb_common as C

REPO = os.path.abspath(os.path.join(C.HERE, "..", ".."))
BANK = os.path.join(REPO, "app", "src", "main", "assets", "questions.json")
STATS = os.path.join(C.HERE, "STATS.md")
CURATED = os.path.join(C.HERE, "curated.json")
PRIORITY = ["curated", "opentdb", "wikidata"]  # earlier wins on duplicates
SCHEMA = ["text", "options", "correctIndex", "category", "difficulty", "explanation", "imageUrl"]
DIFFS = ["easy", "medium", "hard"]
HTML_ENTITY = re.compile(r"&(#\d+|#x[0-9a-fA-F]+|[A-Za-z][A-Za-z0-9]*);")
URL_ENC = re.compile(r"%[0-9A-Fa-f]{2}")


def is_true_false(options):
    return len(options) == 2 and {o.strip().lower() for o in options if isinstance(o, str)} == {"true", "false"}


def drop_reason(q):
    """Return None if the question is valid, else a short reason."""
    opts = q.get("options")
    text = q.get("text")
    if not isinstance(text, str) or not isinstance(opts, list) or not all(isinstance(o, str) for o in opts):
        return "malformed"
    if is_true_false(opts):
        pass
    elif len(opts) != 4 or len({o.strip().lower() for o in opts}) != 4:
        return "options not 4 distinct (or T/F)"
    ci = q.get("correctIndex")
    if not isinstance(ci, int) or isinstance(ci, bool) or not 0 <= ci < len(opts):
        return "correctIndex out of range"
    if not 10 <= len(text) <= 250:
        return "text length not 10-250"
    if any(not 1 <= len(o) <= 80 for o in opts):
        return "option length not 1-80"
    if any(HTML_ENTITY.search(s) or URL_ENC.search(s) for s in [text] + opts):
        return "HTML entity / URL-encoding left over"
    if q.get("category") not in C.APP_TOPICS:
        return "unknown category"
    if q.get("difficulty") not in DIFFS:
        return "bad difficulty"
    return None


def load_sources():
    sources = {"curated": C.load_json(CURATED, [])}
    for name in PRIORITY[1:]:
        sources[name] = C.load_json(os.path.join(C.SOURCES_DIR, name + ".json"), [])
    return sources


def build(sources):
    kept, seen = [], set()
    stats = {"per_source": {}, "drops": collections.Counter(), "templates": collections.defaultdict(list)}
    for name in PRIORITY:
        total = kept_n = dup = 0
        for q in sources.get(name, []):
            total += 1
            reason = drop_reason(q)
            if reason:
                stats["drops"]["%s: %s" % (name, reason)] += 1
                continue
            key = C.normalized_text(q["text"])
            if key in seen:
                dup += 1
                stats["drops"]["%s: duplicate text" % name] += 1
                continue
            seen.add(key)
            kept_n += 1
            kept.append({k: q[k] for k in SCHEMA})
            if name == "wikidata":
                stats["templates"][q.get("template", "?")].append(q["text"] + "  ->  " + q["options"][q["correctIndex"]])
        stats["per_source"][name] = (total, kept_n)
    kept.sort(key=lambda q: (q["category"], q["text"]))
    return kept, stats


def render_stats(kept, stats):
    L = ["# Question bank stats", "", "Generated by `build_bank.py`. Do not edit.", "",
         "Total questions: **%d**" % len(kept), "", "## Per source", "",
         "| Source | Input | Kept |", "|---|---:|---:|"]
    for name in PRIORITY:
        t, k = stats["per_source"][name]
        L.append("| %s | %d | %d |" % (name, t, k))
    L += ["", "## Category x difficulty", "", "| Category | easy | medium | hard | total |", "|---|---:|---:|---:|---:|"]
    grid = collections.Counter((q["category"], q["difficulty"]) for q in kept)
    for cat in sorted({q["category"] for q in kept}):
        row = [grid[(cat, d)] for d in DIFFS]
        L.append("| %s | %d | %d | %d | %d |" % (cat, *row, sum(row)))
    L += ["", "## Dropped", ""]
    if stats["drops"]:
        L += ["| Reason | Count |", "|---|---:|"]
        L += ["| %s | %d |" % (r, n) for r, n in sorted(stats["drops"].items())]
    else:
        L.append("Nothing dropped.")
    L += ["", "## Wikidata samples", ""]
    for tpl in sorted(stats["templates"]):
        items = stats["templates"][tpl]
        step = max(1, len(items) // 3)
        L.append("**%s** (%d kept)" % (tpl, len(items)))
        L.append("")
        L += ["- " + s for s in items[::step][:3]]
        L.append("")
    return "\n".join(L) + "\n"


def main():
    kept, stats = build(load_sources())
    with open(BANK, "w", encoding="utf-8") as f:
        json.dump(kept, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")
    with open(STATS, "w", encoding="utf-8") as f:
        f.write(render_stats(kept, stats))
    print("wrote %d questions to %s" % (len(kept), BANK))
    return 0


if __name__ == "__main__":
    sys.exit(main())
